"""
Prompts for the Skeleton2D (cutout) art route.

Each fighter needs three generated images instead of ~80 animation frames:

    rig_raw/<id>/reference.png   full body, the approved look            (generate FIRST; never cut)
    rig_raw/<id>/parts.png       body parts laid out separately          (attach reference; this is what gets cut)
    rig_raw/<id>/portrait.png    select-screen portrait                  (attach reference)

.png or .jpg both work. Far-side limbs are darkened copies of the near ones (no separate image).
The parts are cut out and placed on the shared Godot skeleton; the animation lives in the rig.
See docs/RIG_PLAN.md for the rest of the pipeline.

    python tools/rig_art/rig_prompts.py prompts   # -> tools/rig_art/prompts/RIG_PROMPTS.md
    python tools/rig_art/rig_prompts.py status
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
ROSTER = HERE / "roster.toml"
RAW = HERE / "rig_raw"
PROMPTS_OUT = HERE / "prompts" / "RIG_PROMPTS.md"

PROVINCES = ("Punjab", "Sindh", "Khyber Pakhtunkhwa", "Balochistan")
IMAGES = ("reference", "parts", "portrait")
RAW_EXTS = (".png", ".jpg", ".jpeg", ".webp")
KEY_NAMES = {"#FF00FF": "magenta", "#00FF00": "green", "#0000FF": "blue"}


@dataclass
class Fighter:
    id: str
    name: str
    title: str
    province: str
    place: str
    setting: str
    gender: str
    look: str
    style: str
    moveset: str = ""
    key: str = "#FF00FF"
    cloth: list[str] = field(default_factory=list)
    props: list[str] = field(default_factory=list)
    rig: str = "medium"


def load_roster(path: Path = ROSTER) -> dict:
    raw = tomllib.loads(path.read_text())
    default_key = raw["style"].get("default_key", "#FF00FF")
    fighters = []
    for f in raw["fighter"]:
        f = dict(f)
        f.setdefault("key", default_key)
        fighters.append(Fighter(**f))
    return {"raw": raw, "fighters": fighters}


def part_names(skel: dict) -> tuple[list[str], list[str]]:
    near = list(skel["core"]) + [f"near {p.replace('_', ' ')}" for p in skel["limbs"]]
    far = [f"far {p.replace('_', ' ')}" for p in skel["limbs"]]
    return near, far


def _bg(key: str) -> str:
    return f"flat solid pure {KEY_NAMES.get(key.upper(), key)} {key.upper()} background"


def build_prompts(roster: dict, f: Fighter) -> dict[str, str]:
    st = roster["raw"]["style"]
    near, _far = part_names(roster["raw"]["skeleton"])
    bg = _bg(f.key)
    same = "Use the attached reference image: the exact same character, same outfit, colours, proportions and art style"
    layout = ("each part drawn in strict side view facing right at the same scale as the reference, "
              "laid out flat in a loose grid with wide empty gaps so that no two parts touch or overlap, "
              "every part has extra rounded material at its joint ends so it can tuck under the neighbouring part "
              "when rotated (round shoulder cap, round elbow, round knee, round hip), "
              "exactly one of each part, no duplicates, no faded or ghost copy of the whole character in the background, "
              "nothing cropped, no labels, no text, no arrows")
    extras = f.cloth + f.props
    extra_txt = (f", plus these as their own separate pieces: {', '.join(extras)}" if extras else "")
    return {
        "reference": ". ".join([
            st["preamble"],
            "Character design reference for a rigged 2D fighter: " + f.look,
            st["rig_pose"] + ", " + bg,
        ]) + ".",
        "parts": ". ".join([
            st["preamble"],
            same,
            "Character parts sheet for 2D cutout animation, the character broken into separate body parts: "
            + ", ".join(near) + extra_txt,
            "The head piece includes the neck; the chest piece runs from shoulders to waist; "
            "the pelvis piece carries the waistband and the top of the lower garment",
            layout + ", " + bg,
        ]) + ".",
        "portrait": ". ".join([
            st["preamble"],
            same,
            "Head and shoulders portrait, three-quarter view, determined expression, " + bg + ", no text",
        ]) + ".",
    }


def raw_file(f: Fighter, image: str, raw_root: Path = RAW) -> Path:
    """The raw image if it exists in any accepted format, else the .png path it should have."""
    for ext in RAW_EXTS:
        p = raw_root / f.id / f"{image}{ext}"
        if p.exists():
            return p
    return raw_root / f.id / f"{image}.png"


def render_markdown(roster: dict, raw_root: Path = RAW) -> str:
    out = [
        "# Rig art prompts (Skeleton2D route)",
        "",
        "Generated by `tools/rig_art/rig_prompts.py prompts`. Do not edit; edit `roster.toml`.",
        "",
        "## How to use",
        "",
        "1. Open Google Flow (or Gemini) with the best image model on offer.",
        "2. Generate the **reference** first. It defines the fighter. Re-roll until it is a clean side view facing right, "
        "arms slightly away from the body, nothing cut off. Save it as `rig_raw/<id>/reference.png`.",
        "   The reference is only the approved look and an assembly guide; it is never cut, so a three-quarter view is OK.",
        "3. Attach `reference.png` as an ingredient/reference image for the parts sheet and the portrait.",
        "4. Parts sheet: this is what gets cut. Re-roll if pieces touch, a part is missing or appears twice, "
        "or a faint ghost of the whole body shows in the background. Missing pieces can be generated on their own "
        "afterwards (same prompt, ask for one part). Far-side limbs are made from the near ones, so don't generate them.",
        "5. Real photos help most: attach a photo of the actual garment or pattern (pakol, ajrak, phulkari, "
        "Swati embroidery, Baloch pudo pocket) next to the reference when the model gets it wrong.",
        "",
        "Rig the `easy` fighters first. `hard` ones have a lot of loose cloth that needs mesh deformation.",
        "",
        "| Province | Urban male | Urban female | Rural male | Rural female |",
        "|---|---|---|---|---|",
    ]
    fs = roster["fighters"]
    for prov in PROVINCES:
        cells = []
        for setting, gender in (("urban", "male"), ("urban", "female"), ("rural", "male"), ("rural", "female")):
            match = [f for f in fs if f.province == prov and f.setting == setting and f.gender == gender]
            cells.append(", ".join(f"[{f.name}](#{f.id}) ({f.rig})" for f in match) or "-")
        out.append(f"| {prov} | " + " | ".join(cells) + " |")
    out.append("")
    for prov in PROVINCES:
        out += [f"## {prov}", ""]
        for f in [f for f in fs if f.province == prov]:
            out += [
                f'<a id="{f.id}"></a>',
                f"### {f.name}: {f.title} (`{f.id}`)",
                "",
                f"*{f.setting.title()} {f.gender}, {f.place}.* Rig: **{f.rig}**. "
                + (f"Takes over `{f.moveset}.json` frame data." if f.moveset else "Moves not designed yet."),
                "",
                f"Style: {f.style}",
                "",
            ]
            if f.cloth or f.props:
                out += [f"Separate pieces: {', '.join(f.cloth + f.props)}", ""]
            for img, text in build_prompts(roster, f).items():
                done = "x" if raw_file(f, img, raw_root).exists() else " "
                out += [f"- [{done}] `rig_raw/{f.id}/{img}.png`", "", "  ```", f"  {text}", "  ```", ""]
    return "\n".join(out)


def cmd_prompts(roster: dict) -> None:
    PROMPTS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PROMPTS_OUT.write_text(render_markdown(roster))
    n = len(roster["fighters"]) * len(IMAGES)
    print(f"wrote {PROMPTS_OUT.relative_to(ROOT)} ({len(roster['fighters'])} fighters, {n} images)")


def cmd_status(roster: dict) -> None:
    for f in roster["fighters"]:
        have = [i for i in IMAGES if raw_file(f, i).exists()]
        missing = [i for i in IMAGES if i not in have]
        mark = "done" if not missing else f"missing {', '.join(missing)}"
        print(f"  {f.id:<10} {f.province:<19} {f.setting:<5} {f.gender:<6} {f.rig:<6} {mark}")


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["prompts", "status"])
    args = ap.parse_args(argv)
    roster = load_roster()
    {"prompts": cmd_prompts, "status": cmd_status}[args.command](roster)


if __name__ == "__main__":
    sys.exit(main())
